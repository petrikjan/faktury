CREATE TABLE record_history (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 entity_type VARCHAR(40) NOT NULL, entity_id BIGINT UNSIGNED NOT NULL,
 version INT UNSIGNED NOT NULL, action VARCHAR(20) NOT NULL,
 data_json JSON NOT NULL, actor_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(actor_id) REFERENCES users(id),
 INDEX(entity_type,entity_id,id)
) ENGINE=InnoDB;
CREATE TABLE delete_confirmations (
 token_hash CHAR(64) PRIMARY KEY, actor_id BIGINT UNSIGNED NOT NULL,
 entity_type VARCHAR(40) NOT NULL, entity_id BIGINT UNSIGNED NOT NULL,
 record_version INT UNSIGNED NOT NULL, expires_at DATETIME(6) NOT NULL,
 FOREIGN KEY(actor_id) REFERENCES users(id), INDEX(expires_at)
) ENGINE=InnoDB;
